    /**
     * The table a module names, as its version tuned it; a number beyond the five falls back to Pro Tracker's.
     */
    static int[] tones(int table, int version) {
        final boolean retuned = version >= RETUNED;
        return switch (table) {
            case SOUND_TRACKER -> SOUND_TRACKER_TONES;
            case ASM -> retuned ? ASM_34 : ASM_33;
            case REAL -> retuned ? REAL_34 : REAL_33;
            case NATURAL -> NATURAL_TONES;
            default -> retuned ? PRO_TRACKER_34 : PRO_TRACKER_33;
        };
    }

    /**
     * How loud a sample line of the given level sounds at the given channel volume.
     */
    static int level(int version, int volume, int level) {
        return (version >= LOUDER_VOLUMES ? VOLUMES_35 : VOLUMES_33)[volume * LEVELS + level];
    }
